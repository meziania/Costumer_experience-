window.CX_I18N = CX_I18N;
window.CX_LANG = "fr";

window.applyCxLang = function applyCxLang(lang) {
  const dict = CX_I18N[lang] || CX_I18N.fr;
  window.CX_LANG = lang;
  document.documentElement.lang = lang;
  localStorage.setItem("cx-lang", lang);

  document.querySelectorAll("[data-i18n]").forEach((el) => {
    const key = el.getAttribute("data-i18n");
    if (dict[key] != null) el.textContent = dict[key];
  });

  document.querySelectorAll("[data-i18n-html]").forEach((el) => {
    const key = el.getAttribute("data-i18n-html");
    if (dict[key] != null) el.innerHTML = dict[key];
  });

  document.querySelectorAll("[data-i18n-placeholder]").forEach((el) => {
    const key = el.getAttribute("data-i18n-placeholder");
    if (dict[key] != null) el.setAttribute("placeholder", dict[key]);
  });

  document.querySelectorAll("[data-i18n-aria]").forEach((el) => {
    const key = el.getAttribute("data-i18n-aria");
    if (dict[key] != null) el.setAttribute("aria-label", dict[key]);
  });

  const title = dict["meta.title"];
  const desc = dict["meta.desc"];
  if (title) document.title = title;
  const meta = document.querySelector('meta[name="description"]');
  if (meta && desc) meta.setAttribute("content", desc);

  document.querySelectorAll(".lang-btn").forEach((btn) => {
    const active = btn.getAttribute("data-lang") === lang;
    btn.classList.toggle("is-active", active);
    btn.setAttribute("aria-pressed", String(active));
  });

  const submitBtn = document.getElementById("submit-btn");
  if (submitBtn && !submitBtn.disabled) {
    submitBtn.textContent = dict["form.submit"];
  }

  const toastText = document.querySelector(".toast__text");
  if (toastText) toastText.textContent = dict["form.toast"];
};
